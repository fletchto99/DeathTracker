local Matcher = require("src/matcher")
local A = { level = 0, x = 100, z = 100 }
local B = { level = 0, x = 101, z = 100 }
local FAR = { level = 0, x = 110, z = 100 }
local ABOVE = { level = 1, x = 100, z = 100 }
local passed = 0
local function test(name, run)
    local ok, err = pcall(run)
    assert(ok, name .. ": " .. tostring(err))
    passed = passed + 1
end
local function new(name)
    name = name or "alice"
    local counts, logs = {}, {}
    local matcher = Matcher.new(function(name)
        counts[name] = (counts[name] or 0) + 1
    end, function(...) logs[#logs + 1] = { ... } end)
    matcher:localPosition(A)
    matcher:observePlayer("a", name, A)
    matcher:advance(160)
    matcher:observePlayer("a", name, A)
    return matcher, counts, logs
end
local function birth(m, key, position, owner)
    m:groundChange(key or "g", position or A, 0, 1, owner == true, true)
end
local function scene()
    local m, counts = new()
    m:removePlayer("a")
    birth(m)
    return m, counts
end
local function collect(m, key, inventoryFirst)
    key = key or "g"
    m:select(key)
    if inventoryFirst then m:inventory(1, false) end
    m:groundChange(key, A, 1, 0, false, true)
    if not inventoryFirst then m:inventory(1, false) end
    m:finishPacket()
end
local function settle(m) m:advance(400) end
local function zero(counts) assert(next(counts) == nil, "unexpected credit") end

test("both event orders count only after collection and attribution settle", function()
    for _, inventoryFirst in ipairs({ false, true }) do
        local m, counts = scene()
        zero(counts)
        collect(m, "g", inventoryFirst)
        zero(counts)
        settle(m)
        assert(counts.alice == 1)
        m:finishPacket()
        m:advance(500)
        assert(counts.alice == 1)
    end
end)
test("bone may appear before player removal", function()
    local m, counts = new()
    birth(m)
    m:advance(165)
    m:removePlayer("a")
    collect(m)
    settle(m)
    assert(counts.alice == 1)
end)
test("world level and exact death tile matter", function()
    for _, position in ipairs({ B, ABOVE }) do
        local m, counts = new()
        m:removePlayer("a")
        birth(m, "g", position)
        m:localPosition(position)
        m:select("g")
        m:groundChange("g", position, 1, 0, false, true)
        m:inventory(1, false)
        m:finishPacket()
        settle(m)
        zero(counts)
    end
end)
test("a previously unknown name is credited without any configuration", function()
    local m, counts = new("stranger")
    m:removePlayer("a")
    birth(m)
    collect(m)
    settle(m)
    assert(counts.stranger == 1)
end)
test("an unresolved name cannot receive credit or remove ambiguity", function()
    local m, counts = new()
    m:observePlayer("unknown", nil, A)
    m:removePlayer("unknown")
    m:removePlayer("a")
    birth(m)
    collect(m)
    settle(m)
    zero(counts)
end)
test("an unresolved name elsewhere is not mistaken for a returning candidate", function()
    local m, counts = scene()
    collect(m)
    m:observePlayer("unknown", nil, FAR)
    settle(m)
    assert(counts.alice == 1)
end)
test("disappearance without a bone never counts", function()
    local m, counts = new()
    m:removePlayer("a")
    m:inventory(1, false)
    settle(m)
    zero(counts)
end)
test("bone without disappearance never counts", function()
    local m, counts = new()
    m.players = {}
    birth(m)
    collect(m)
    settle(m)
    zero(counts)
end)
test("ground removal or inventory increase alone cannot complete an intent", function()
    for _, onlyGround in ipairs({ true, false }) do
        local m, counts = scene()
        m:select("g")
        if onlyGround then m:groundChange("g", A, 1, 0, false, true)
        else m:inventory(1, false) end
        m:finishPacket()
        settle(m)
        zero(counts)
    end
end)
test("click without completion times out", function()
    local m, counts = scene()
    m:select("g")
    m:advance(261)
    m:groundChange("g", A, 1, 0, false, true)
    m:inventory(1, false)
    m:finishPacket()
    settle(m)
    zero(counts)
end)
test("pre-click inventory gain cannot confirm a later pickup", function()
    local m, counts = scene()
    m:inventory(1, false)
    m:select("g")
    m:groundChange("g", A, 1, 0, false, true)
    m:finishPacket()
    settle(m)
    zero(counts)
end)
test("different server packets are rejected in either order", function()
    for _, inventoryFirst in ipairs({ true, false }) do
        local m, counts = scene()
        m:select("g")
        if inventoryFirst then m:inventory(1, false)
        else m:groundChange("g", A, 1, 0, false, true) end
        m:finishPacket()
        if inventoryFirst then m:groundChange("g", A, 1, 0, false, true)
        else m:inventory(1, false) end
        m:finishPacket()
        settle(m)
        zero(counts)
    end
end)
test("additional inventory changes and multiple bones are rejected", function()
    for _, change in ipairs({ { 2, false }, { 1, true }, { -1, false } }) do
        local m, counts = scene()
        m:select("g")
        m:groundChange("g", A, 1, 0, false, true)
        m:inventory(change[1], change[2])
        m:finishPacket()
        settle(m)
        zero(counts)
    end
end)
test("repeated inventory notifications with no delta do not double count", function()
    local m, counts = scene()
    m:select("g")
    m:inventory(1, false)
    m:inventory(0, false)
    m:groundChange("g", A, 1, 0, false, true)
    m:finishPacket()
    settle(m)
    assert(counts.alice == 1)
end)
test("old bones seeded at load cannot acquire provenance", function()
    local m, counts = new()
    m:seedGround("g", A, 1)
    m:removePlayer("a")
    collect(m)
    settle(m)
    zero(counts)
end)
test("stack ambiguity and unresolved aggregate changes are rejected", function()
    for _, mode in ipairs({ "multiple", "increase", "mismatch" }) do
        local m, counts = scene()
        if mode == "multiple" then birth(m, "second")
        elseif mode == "increase" then
            m:groundChange("g", A, 1, 2, false, true)
            m:groundChange("g", A, 2, 1, false, true)
        else m:groundChange("g", A, 1, 1, false, false) end
        collect(m)
        settle(m)
        zero(counts)
    end
end)
test("multiple co-located players including strangers are ambiguous", function()
    for _, otherName in ipairs({ "bob", "stranger" }) do
        local m, counts = new()
        m:observePlayer("b", otherName, A)
        m:removePlayer("b")
        m:removePlayer("a")
        birth(m)
        collect(m)
        settle(m)
        zero(counts)
    end
end)
test("a co-located player moving away still makes attribution ambiguous", function()
    local m, counts = new()
    m:observePlayer("b", "stranger", A)
    m:observePlayer("b", "stranger", FAR)
    m:removePlayer("a")
    birth(m)
    collect(m)
    settle(m)
    zero(counts)
end)
test("crowding at disappearance is retained even if the bone appears later", function()
    local m, counts = new()
    m:observePlayer("b", "stranger", A)
    m:observePlayer("b", "stranger", FAR)
    m:advance(210)
    m:observePlayer("a", "alice", A)
    m:removePlayer("a")
    m:advance(260)
    birth(m)
    collect(m)
    settle(m)
    zero(counts)
end)
test("a late same-tile arrival invalidates uncommitted attribution", function()
    local m, counts = scene()
    collect(m)
    m:advance(180)
    m:observePlayer("b", "stranger", A)
    settle(m)
    zero(counts)
end)
test("a returning player invalidates the departure", function()
    for _, afterMatch in ipairs({ true, false }) do
        local m, counts = scene()
        if afterMatch then m:advance(281) end
        m:observePlayer("a2", "alice", FAR)
        collect(m)
        settle(m)
        zero(counts)
    end
end)
test("local-owned and unknown-ownership bones are not attributed", function()
    for _, owner in ipairs({ true, "unknown" }) do
        local m, counts = new()
        m:removePlayer("a")
        m:groundChange("g", A, 0, 1, owner == true and true or nil, true)
        collect(m)
        settle(m)
        zero(counts)
    end
end)
test("distant intent, walking away, and nearby competitors are rejected", function()
    for _, mode in ipairs({ "distant", "walk", "competitor" }) do
        local m, counts = scene()
        if mode == "distant" then m:localPosition(FAR) end
        m:select("g")
        if mode == "walk" then m:localPosition(FAR) end
        if mode == "competitor" then m:observePlayer("b", "stranger", B) end
        m:groundChange("g", A, 1, 0, false, true)
        m:inventory(1, false)
        m:finishPacket()
        settle(m)
        zero(counts)
    end
end)
test("cancellation and repeated clicks cannot resurrect a pickup", function()
    for _, repeatClick in ipairs({ false, true }) do
        local m, counts = scene()
        m:select("g")
        if repeatClick then m:select("g") else m:cancel("Walk") end
        m:groundChange("g", A, 1, 0, false, true)
        m:inventory(1, false)
        m:finishPacket()
        settle(m)
        zero(counts)
    end
end)
test("competing same-item changes cancel the pending collection", function()
    local m, counts = scene()
    m:select("g")
    m:groundChange("other", FAR, 1, 0, false, true)
    m:groundChange("g", A, 1, 0, false, true)
    m:inventory(1, false)
    m:finishPacket()
    settle(m)
    zero(counts)
end)
test("one disappearance cannot be reused for re-dropped bones", function()
    local m, counts = scene()
    collect(m)
    settle(m)
    assert(counts.alice == 1)
    m:inventory(-1, false)
    birth(m, "redropped")
    collect(m, "redropped")
    m:advance(700)
    assert(counts.alice == 1)
end)
test("reappearance of a consumed ground key never creates another death", function()
    local m, counts = scene()
    collect(m)
    settle(m)
    birth(m)
    collect(m)
    m:advance(700)
    assert(counts.alice == 1)
end)
test("warmup, stale positions, and a moving departure are rejected", function()
    for _, mode in ipairs({ "warmup", "stale", "moving" }) do
        local m, counts = new()
        if mode == "warmup" then
            m:reset("world")
            m:observePlayer("a", "alice", A)
        elseif mode == "stale" then m:advance(171)
        else m:observePlayer("a", "alice", B); m:observePlayer("a", "alice", A) end
        m:removePlayer("a")
        birth(m)
        collect(m)
        settle(m)
        zero(counts)
    end
end)
test("correlation window includes 60 ticks and rejects 61", function()
    for _, gap in ipairs({ 60, 61 }) do
        local m, counts = new()
        m:removePlayer("a")
        m:advance(160 + gap)
        birth(m)
        collect(m)
        settle(m)
        if gap == 60 then assert(counts.alice == 1) else zero(counts) end
    end
end)
test("pending attribution expires after 30 seconds", function()
    local m, counts = scene()
    m:advance(1661)
    collect(m)
    m:advance(2000)
    zero(counts)
end)
test("lifecycle reset clears pending evidence but not prior counts", function()
    local m, counts = scene()
    collect(m)
    m:reset("world")
    settle(m)
    zero(counts)
end)
test("a fresh, stably observed later disappearance can count again", function()
    local m, counts = scene()
    collect(m)
    settle(m)
    m:observePlayer("a2", "alice", A)
    m:advance(560)
    m:observePlayer("a2", "alice", A)
    m:removePlayer("a2")
    birth(m, "g2")
    collect(m, "g2")
    m:advance(700)
    assert(counts.alice == 2)
end)
return passed
